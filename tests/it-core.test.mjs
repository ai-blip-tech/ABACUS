const assertSafeGuidance = (turn, target) => {
  assert.ok(turn.actions?.length > 0);
  assert.ok(turn.actions.every((action) => action.target === target));
  assert.ok(turn.actions.every((action) => !["click", "submit", "generate"].includes(action.type)));
};

