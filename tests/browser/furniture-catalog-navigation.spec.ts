import { expect, test } from "@playwright/test";

test("discount cards and details allow adding made-to-order products to the project",async({page})=>{
  await page.route("**/api/auth/me",route=>route.fulfill({json:{user:{id:"catalog-user",firstName:"Иван",lastName:"Петров",role:"user"}}}));
  const base={brand:"FUGA",article:"TEST",image:"/catalog-brands/fuga.png",images:[],available:false,price:600,oldPrice:1000,parameters:[],widthMm:100,depthMm:100,heightMm:100};
  await page.route("**/api/catalog?**",route=>route.fulfill({json:{products:[{...base,id:"sale",name:"Товар со скидкой"},{...base,id:"regular",name:"Обычный товар",oldPrice:0}],total:2,productBrands:[],categorySubtypes:{},categoryColors:{},unavailableSources:[]}}));
  await page.goto("/?catalog=furniture#студия");
  const cards=page.locator(".room-catalog-card");
  await expect(page.getByRole("button",{name:"Выбрано товаров — 0",exact:true})).toBeVisible();
  await expect(cards.first().locator(".room-catalog-discount")).toHaveText("−40%");
  await expect(cards.first().locator("del")).toContainText("1 000");
  await expect(cards.last().locator(".room-catalog-discount")).toHaveCount(0);
  await expect(cards.last().locator("del")).toHaveCount(0);
  await expect(cards.first().getByText("Под заказ",{exact:true})).toBeVisible();
  await expect(cards.last().getByRole("button",{name:"Выбрать",exact:true})).toBeEnabled();
  await cards.last().getByRole("button",{name:"Выбрать",exact:true}).click();
  await expect(cards.last().getByRole("button",{name:"Уже выбран",exact:true})).toBeVisible();
  await expect(page.getByRole("button",{name:"Выбрано товаров — 1",exact:true})).toBeVisible();
  await cards.first().locator(".room-catalog-card-body").click();
  const detail=page.getByRole("complementary",{name:"Подробности товара"});
  await expect(detail.getByText("Под заказ",{exact:true})).toBeVisible();
  await expect(detail.getByRole("button",{name:"Выбрать для проекта"})).toBeEnabled();
  await detail.getByRole("button",{name:"Выбрать для проекта"}).click();
  await detail.getByRole("button",{name:"Закрыть подробности"}).click();
  await expect(cards.first().getByRole("button",{name:"Уже выбран",exact:true})).toBeVisible();
  const returnButton=page.getByRole("button",{name:"Выбрано товаров — 2",exact:true});
  await expect(returnButton).toBeVisible();
  await cards.first().getByRole("button",{name:"Уже выбран",exact:true}).click();
  await expect(page.getByRole("button",{name:"Выбрано товаров — 1",exact:true})).toBeVisible();
  await cards.first().getByRole("button",{name:"Выбрать",exact:true}).click();
  await returnButton.hover();
  await expect(returnButton).toHaveCSS("color","rgb(255, 255, 255)");
  await returnButton.click();
  await expect(page.locator(".studio-material-card")).toHaveCount(2);
  await page.getByRole("button",{name:"⌕ Каталог",exact:true}).click();
  await expect(page.getByRole("button",{name:"Выбрано товаров — 2",exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Закрыть каталог",exact:true}).click();
  await expect(page.getByRole("dialog",{name:"Каталог брендов партнеров"})).toHaveCount(0);
});

test("catalog exposes all brands and collapsible category variants with stock off by default",async({page},testInfo)=>{
  const requests:URL[]=[];
  const names=["NORR Møbler","NORR Carpets","FUGA","SEYVAA PARIS","MOBLIBERICA","LEVE HOME","GoMoon"];
  await page.route("**/api/auth/me",route=>route.fulfill({json:{user:{id:"catalog-user",firstName:"Иван",lastName:"Петров",email:"catalog@example.test",role:"user"}}}));
  await page.route("**/api/catalog?**",route=>{
    requests.push(new URL(route.request().url()));
    return route.fulfill({json:{products:[],total:0,productBrands:names.map(name=>({id:`brand:${name.toLowerCase()}`,name,count:10})),categoryColors:{sofa:["Бежевый","Белый","Чёрный"]},categorySubtypes:{sofa:["Кушетка","Модуль","Прямой","П-образный","Угловой"],chair:["Стул барный","Стул интерьерный","Стул крутящийся"],technical_light:["Треки","Трековые светильники","Светильники","Источники питания","Комплектующие"]},unavailableSources:[]}});
  });
  await page.goto("/?catalog=furniture#студия");
  const catalog=page.getByRole("dialog",{name:"Каталог брендов партнеров"});
  await expect(catalog.getByRole("heading",{name:"Выберите марку"})).toHaveCount(0);
  const stock=catalog.getByRole("switch",{name:"В наличии",exact:true});
  await expect(stock).not.toBeChecked();
  for(const name of names)await expect(catalog.getByRole("button",{name:new RegExp(name)})).toBeVisible();
  expect(requests[0].searchParams.has("available")).toBe(false);
  const colors=catalog.locator(".room-catalog-colors");
  await expect(colors).toHaveCount(0);
  await expect.poll(()=>requests.at(-1)?.searchParams.has("color")).toBe(false);
  const types=catalog.locator(".room-catalog-types:not(.room-catalog-colors):not(.room-catalog-feature)");
  for(const [title,key] of [["Реклайнер","recliner"],["Спальное место","sleeper"],["Оттоманка","ottoman"]]){
    await catalog.locator(".room-catalog-feature").filter({hasText:title}).locator("summary").click();
    const group=catalog.getByRole("group",{name:title,exact:true});
    await group.getByRole("button",{name:"Нет",exact:true}).click();
    await expect.poll(()=>requests.at(-1)?.searchParams.get(key)).toBe("no");
    await group.getByRole("button",{name:"Неважно",exact:true}).click();
  }
  await expect(types).not.toHaveAttribute("open");
  await expect(catalog.getByRole("button",{name:"Стул",exact:true})).not.toBeVisible();
  await types.locator("summary").click();
  await catalog.getByRole("button",{name:"Диван",exact:true}).click();
  const sofa=catalog.getByRole("group",{name:"Варианты: Диван"});
  for(const variant of ["Кушетка","Модуль","Прямой","П-образный","Угловой"])await expect(sofa.getByRole("button",{name:variant,exact:true})).toBeVisible();
  await sofa.getByRole("button",{name:"Прямой",exact:true}).click();
  await expect.poll(()=>requests.at(-1)?.searchParams.get("subtype")).toBe("Прямой");
  await expect(sofa.getByRole("button",{name:"Угловой",exact:true})).toBeVisible();
  await catalog.getByRole("button",{name:/FUGA/}).click();
  await expect.poll(()=>requests.at(-1)?.searchParams.get("brands")).toBe("brand:fuga");
  await stock.check();
  await expect.poll(()=>requests.at(-1)?.searchParams.get("available")).toBe("1");
  const switchLayout=await catalog.locator(".room-catalog-available").evaluate(label=>{
    const track=label.querySelector(".room-catalog-switch-track")!;
    const text=label.lastElementChild!;
    const rect=track.getBoundingClientRect(),textRect=text.getBoundingClientRect();
    const knob=getComputedStyle(track,"::after");
    return {width:rect.width,right:rect.right,textLeft:textRect.left,knobEnd:parseFloat(knob.left)+parseFloat(knob.width)+16};
  });
  expect(switchLayout.width).toBe(38);
  expect(switchLayout.right).toBeLessThan(switchLayout.textLeft);
  expect(switchLayout.knobEnd).toBeLessThanOrEqual(switchLayout.width);
  await catalog.getByRole("button",{name:"Стул",exact:true}).click();
  await expect(catalog.locator(".room-catalog-feature")).toHaveCount(0);
  const chairs=catalog.getByRole("group",{name:"Варианты: Стул"});
  await expect(chairs.getByRole("button",{name:"Стул барный",exact:true})).toBeVisible();
  await expect.poll(()=>requests.at(-1)?.searchParams.get("type")).toBe("chair");
  await expect.poll(()=>requests.at(-1)?.searchParams.has("subtype")).toBe(false);
  await catalog.getByRole("button",{name:"Сбросить всё",exact:true}).click();
  await expect(stock).not.toBeChecked();
  await expect.poll(()=>requests.at(-1)?.searchParams.has("available")).toBe(false);
  await catalog.getByRole("button",{name:/GoMoon/}).click();
  await expect.poll(()=>requests.at(-1)?.searchParams.get("type")).toBe("technical_light");
  await expect.poll(()=>requests.at(-1)?.searchParams.get("brands")).toBe("brand:gomoon");
  await catalog.getByRole("button",{name:"Технический свет",exact:true}).click();
  const technical=catalog.getByRole("group",{name:"Варианты: Технический свет"});
  await expect(technical.getByRole("button",{name:"Треки",exact:true})).toBeVisible();
  await expect(technical.getByRole("button",{name:"Трековые светильники",exact:true})).toBeVisible();
  await catalog.getByRole("textbox",{name:"Поиск по каталогу"}).fill("LEV01060");
  await expect.poll(()=>requests.at(-1)?.searchParams.get("q")).toBe("LEV01060");
  await expect(catalog.getByRole("status")).toContainText("Поиск по всему каталогу");
  await catalog.getByRole("combobox",{name:"Сортировка"}).selectOption("discount_desc");
  await expect.poll(()=>requests.at(-1)?.searchParams.get("sort")).toBe("discount_desc");
  const positions=await catalog.evaluate(root=>{const stock=root.querySelector(".room-catalog-available")!.getBoundingClientRect();const type=root.querySelector(".room-catalog-types")!.getBoundingClientRect();return{stock:stock.top,type:type.top};});
  expect(positions.stock).toBeLessThan(positions.type);
  if(testInfo.project.name==="chromium-1440")await page.screenshot({path:"/private/tmp/room-design-catalog-updated.png",fullPage:false});
});
